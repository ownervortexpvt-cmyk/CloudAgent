/**
 * pub.dev dependency management for Flutter/Dart projects.
 *
 * The agent's install_package tool used to run `npm install <pkg>` for EVERY
 * project — but Flutter packages (speech_to_text, flutter_tts, provider…)
 * live on pub.dev, not npm, so installs returned E404 and the agent kept
 * retrying (the user saw repeated "404 Not Found - speech_to_text" walls).
 *
 * This module records REAL pub.dev dependencies into pubspec.yaml:
 *   - parses "name", "name:1.2.3" and "name@^1.2.3" specs
 *   - resolves the latest REAL version from the pub.dev API (best effort;
 *     falls back to `any` if the registry is unreachable — recorded
 *     honestly, never invented)
 *   - inserts / updates the dependency inside pubspec.yaml `dependencies:`
 *
 * No Flutter SDK is required for the record step: pubspec.yaml is the source
 * of truth and `flutter pub get` resolves it on any machine that has the SDK
 * (or after install_sdk flutter succeeds).
 */
import * as storage from './storage'

export interface ParsedPubSpec {
  name: string
  constraint: string | null // null → resolve latest from pub.dev
}

export interface PubDepResult {
  ok: boolean
  name: string
  constraint: string
  source: 'specified' | 'pub.dev' | 'fallback-any'
  created: boolean // pubspec.yaml did not exist and was created
  updated: boolean // existing dependency line replaced (vs freshly inserted)
  error?: string
}

// pub.dev names: lowercase letters/digits/underscores, start with a letter.
const PUB_NAME_RE = /^[a-z][a-z0-9_]{0,127}$/
// A sane version-constraint charset (covers ^1.2.3, >=1.0.0 <2.0.0, any, 2.x…)
const CONSTRAINT_RE = /^[0-9^~><=*.xX anyA-Za-z-]+$/

/**
 * Parse an install spec into a pub package name + optional constraint.
 * Accepted: "speech_to_text", "speech_to_text:5.0.1", "speech_to_text@^5.0.1".
 * Returns null for anything that cannot be a pub package.
 */
export function parsePubSpec(raw: string): ParsedPubSpec | null {
  const spec = (raw || '').trim()
  if (!spec || spec.length > 160) return null
  const m = spec.match(/^([A-Za-z][A-Za-z0-9_]*)(?:[:@]\s*(.+))?$/)
  if (!m) return null
  const name = m[1].toLowerCase()
  if (!PUB_NAME_RE.test(name)) return null
  let constraint = (m[2] || '').trim() || null
  if (constraint) {
    constraint = constraint.replace(/^v/, '')
    if (!CONSTRAINT_RE.test(constraint)) return null
    // Bare semver "5.0.1" → caret constraint "5.0.1" is what the user typed;
    // keep it exact — do NOT silently upgrade their pin.
    if (/^\d+\.\d+\.\d+$/.test(constraint)) constraint = `^${constraint}`
  }
  return { name, constraint }
}

/**
 * Resolve the latest published version of a pub.dev package. Returns null on
 * any failure (offline, 404, rate limit) — callers must handle honestly.
 */
export async function fetchPubLatest(name: string): Promise<string | null> {
  try {
    const res = await fetch(`https://pub.dev/api/packages/${encodeURIComponent(name)}`, {
      signal: AbortSignal.timeout(8000),
      headers: { accept: 'application/json' },
    })
    if (!res.ok) return null
    const j: any = await res.json()
    const v = j?.latest?.version
    return typeof v === 'string' && /^\d+[0-9A-Za-z.+*-]*$/.test(v) ? v : null
  } catch {
    return null
  }
}

/** Minimal but valid pubspec for projects where none exists yet. */
function minimalPubspec(): string {
  return [
    'name: cloud_agent_app',
    'description: A new Flutter project generated by Cloud Agent.',
    'publish_to: none',
    'version: 1.0.0',
    '',
    'environment:',
    "  sdk: '>=3.0.0 <4.0.0'",
    '',
    'dependencies:',
    '  flutter:',
    '    sdk: flutter',
    '',
    'dev_dependencies:',
    '  flutter_lints: ^3.0.0',
    '',
    'flutter:',
    '  uses-material-design: true',
    '',
  ].join('\n')
}

/**
 * Insert or update `  name: constraint` under the top-level `dependencies:`
 * key of a pubspec.yaml. Line-oriented and deliberately conservative:
 * comments, ordering and all other sections are preserved untouched.
 */
function upsertDependency(yaml: string, name: string, constraint: string): { yaml: string; updated: boolean; inserted: boolean } {
  const lines = yaml.split('\n')
  const depIdx = lines.findIndex((l) => /^dependencies:\s*(#.*)?$/.test(l))

  if (depIdx === -1) {
    // No dependencies section — append one at the end.
    const trimmed = yaml.replace(/\n+$/, '')
    const block = `\n\ndependencies:\n  ${name}: ${constraint}\n`
    return { yaml: trimmed + block, updated: false, inserted: true }
  }

  // Find the section extent (next top-level key) and look for the package.
  let end = lines.length
  for (let i = depIdx + 1; i < lines.length; i++) {
    if (/^[A-Za-z_][A-Za-z0-9_-]*:\s*(#.*)?$/.test(lines[i])) {
      end = i
      break
    }
  }
  for (let i = depIdx + 1; i < end; i++) {
    const key = lines[i].match(/^(\s*)([A-Za-z_][A-Za-z0-9_-]*)(\s*):(.*)$/)
    if (key && key[2] === name && key[1].length >= 2) {
      lines[i] = `${key[1]}${name}: ${constraint}`
      return { yaml: lines.join('\n'), updated: true, inserted: false }
    }
  }
  // Insert directly under `dependencies:` — always valid YAML.
  lines.splice(depIdx + 1, 0, `  ${name}: ${constraint}`)
  return { yaml: lines.join('\n'), updated: false, inserted: true }
}

/**
 * Record a pub.dev dependency in the project's pubspec.yaml.
 * Constraint resolution order: user-specified → pub.dev latest → `any`.
 */
export async function addPubDependency(projectId: string, rawSpec: string): Promise<PubDepResult> {
  const parsed = parsePubSpec(rawSpec)
  if (!parsed) {
    return { ok: false, name: String(rawSpec || '').slice(0, 60), constraint: '', source: 'fallback-any', created: false, updated: false, error: `"${String(rawSpec).slice(0, 60)}" is not a valid pub.dev package name (lowercase_with_underscores, optionally "name:version")` }
  }

  let constraint = parsed.constraint
  let source: PubDepResult['source'] = 'specified'
  if (!constraint) {
    const latest = await fetchPubLatest(parsed.name)
    if (latest) {
      constraint = `^${latest}`
      source = 'pub.dev'
    } else {
      constraint = 'any'
      source = 'fallback-any'
    }
  }

  const existed = storage.existsFile(projectId, 'pubspec.yaml')
  const yaml = existed ? storage.readFile(projectId, 'pubspec.yaml') : minimalPubspec()
  const res = upsertDependency(yaml, parsed.name, constraint)
  storage.writeFile(projectId, 'pubspec.yaml', res.yaml.endsWith('\n') ? res.yaml : res.yaml + '\n')

  return {
    ok: true,
    name: parsed.name,
    constraint,
    source,
    created: !existed,
    updated: res.updated,
  }
}
