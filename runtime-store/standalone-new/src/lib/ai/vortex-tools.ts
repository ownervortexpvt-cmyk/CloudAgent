/**
 * v142 — VORTEX ECOSYSTEM auto-provision (owner request: "cloud agent automatic
 * ei gulo set-up kore dibe"). When the AI builds an app that needs a backend —
 * login/OTP, database, file storage — it calls this tool ONCE and the app gets
 * a fully provisioned VORTEX VaaS backend: project + collections + CLIENT key
 * (safe for the app's client bundle) + ADMIN key (owner-only) + SDK snippet,
 * written straight into the project so the generated code can import it.
 */

/** Shareable provision+write pipeline (used by the AI tool AND the runAgent auto-hook). */
export async function ensureVortexBackend(projectId: string, collections: string[]): Promise<{ ok: boolean; provisioned: boolean; vaasProjectId?: string; clientKey?: string; baseUrl?: string; error?: string }> {
  if (!vortexConfigured()) return { ok: false, provisioned: false, error: 'VORTEX ecosystem not wired (VORTEX_PLATFORM_KEY missing)' }
  const existing = await db.projectSetting.findUnique({ where: { projectId_key: { projectId, key: 'vortex.vaas' } } })
  if (existing) {
    const stored = JSON.parse(existing.value || '{}')
    return { ok: true, provisioned: true, vaasProjectId: stored.vaasProjectId, clientKey: stored.clientKey, baseUrl: stored.baseUrl }
  }
  const project = await db.project.findUnique({ where: { id: projectId } })
  if (!project) return { ok: false, provisioned: false, error: 'project not found' }
  const res = await provisionVaasBackend(project.name || 'Cloud Agent App', collections)
  if (!res.ok) return { ok: false, provisioned: false, error: res.error || 'VaaS provision failed' }
  const payload = {
    vaasProjectId: res.projectId,
    clientKey: res.clientKey,
    adminKey: res.adminKey, // stored server-side; surfaced once to the owner via the Publish dialog
    baseUrl: res.baseUrl,
    collections,
    snippet: res.snippet,
    provisionedAt: new Date().toISOString(),
  }
  await db.projectSetting.upsert({
    where: { projectId_key: { projectId, key: 'vortex.vaas' } },
    create: { projectId, key: 'vortex.vaas', value: JSON.stringify(payload) },
    update: { value: JSON.stringify(payload) },
  })
  await writeVortexProjectFiles(projectId, payload, collections)
  return { ok: true, provisioned: true, vaasProjectId: res.projectId, clientKey: res.clientKey, baseUrl: res.baseUrl }
}

/** Write vortex.config.js + VORTEX_BACKEND.md into the project (disk + DB row). */
async function writeVortexProjectFiles(projectId: string, payload: any, collections: string[]) {
  const cfg = `// VORTEX VaaS backend configuration (auto-generated by CLOUD AGENT)
// Client-side config — the CLIENT key is safe to ship (like a Firebase apiKey).
// The ADMIN key is NOT here — it lives in the project settings (owner only).
window.VORTEX_CONFIG = {
  projectId: '${payload.vaasProjectId}',
  clientKey: '${payload.clientKey}',
  baseUrl: '${payload.baseUrl}',
  collections: ${JSON.stringify(payload.collections || collections)},
}
`
  storage.writeFile(projectId, 'vortex.config.js', cfg)
  await safeUpsertFile(projectId, 'vortex.config.js', cfg)
  const guide = payload.snippet || `// VORTEX VaaS SDK quickstart`
  const md = `# VORTEX Backend (provisioned)\n\nprojectId: ${payload.vaasProjectId}\nCollections: ${(payload.collections || collections).join(', ')}\n\n${guide}\n`
  storage.writeFile(projectId, 'VORTEX_BACKEND.md', md)
  await safeUpsertFile(projectId, 'VORTEX_BACKEND.md', md)
}

/**
 * v142 deterministic AUTO-PROVISION hook (owner: "cloud agent automatic ei gulo
 * set-up kore dibe"). Called at the END of every agent run. Provisions the
 * VORTEX backend when ALL of:
 *   1. the ecosystem is wired (VORTEX_PLATFORM_KEY present)
 *   2. no provision exists for the project yet
 *   3. the project shipped real UI files (an app, not a bare config/tool)
 *   4. the prompt or the built index.html shows backend need (login/users/data/uploads)
 * Never throws — a provision failure must not fail the run.
 */
export async function maybeAutoProvisionVortex(projectId: string, prompt: string): Promise<{ provisioned: boolean; vaasProjectId?: string; reason?: string }> {
  try {
    if (!vortexConfigured()) return { provisioned: false, reason: 'not wired' }
    const existing = await db.projectSetting.findUnique({ where: { projectId_key: { projectId, key: 'vortex.vaas' } } })
    if (existing) return { provisioned: false, reason: 'already provisioned' }
    const needRe = /(\blogin\b|\bsign\s?in\b|\bsign\s?up\b|\bauth\b|\botp\b|\bpassword\b|\baccount\b|\buser\b|\busers\b|\bdatabase\b|\bdb\b|\bstorage\b|\bupload\b|\bcart\b|\border\b|\bordered\b|\bnotes\b|\btodo\b|\btask\b|\bchat\b|\bmessage\b|\bpost\b|\bcomment\b|\bprofile\b|\bbookmark\b|\bfavorite\b|\bscore\b|\bleaderboard\b|\bsubscribe\b|\bpayment\b|\bcheckout\b|\brecipe\b)/i
    const haystack = `${prompt.slice(0, 4000)} ${safeReadIndex(projectId)}`
    if (!needRe.test(haystack)) return { provisioned: false, reason: 'no backend-need signal' }
    if (!looksLikeAnApp(projectId)) return { provisioned: false, reason: 'not an app project' }
    const r = await ensureVortexBackend(projectId, ['users', 'posts', 'settings'])
    return r.ok ? { provisioned: true, vaasProjectId: r.vaasProjectId } : { provisioned: false, reason: r.error }
  } catch (e: any) {
    return { provisioned: false, reason: e?.message || 'auto-provision failed' }
  }
}

function safeReadIndex(projectId: string): string {
  // the AI nests apps in subdirs (notes-app/, recipe-box-app/) — walk the tree
  for (const t of walkHtmlFiles(projectId, '', 0)) {
    try { return storage.readFile(projectId, t).slice(0, 60000) } catch {}
  }
  return ''
}

/** Find up to 3 index.html files anywhere under the project (depth-capped). */
function walkHtmlFiles(projectId: string, dir: string, depth: number): string[] {
  if (depth > 4) return []
  const out: string[] = []
  let entries: Array<{ name: string; isDirectory: boolean; path: string }> = []
  try {
    const tree = storage.listTree(projectId, dir || '.') as any
    const flat = (node: any, base: string): void => {
      for (const child of node.children || []) {
        const p = base ? `${base}/${child.name}` : child.name
        if (child.isDirectory) flat(child, p)
        else entries.push({ name: child.name, isDirectory: false, path: p })
      }
    }
    flat(tree, dir)
  } catch { return [] }
  for (const e of entries) {
    if (e.name === 'index.html' && !e.path.includes('node_modules')) out.push(e.path)
    if (out.length >= 3) break
  }
  return out
}

function looksLikeAnApp(projectId: string): boolean {
  // any real code artifact (not only .gitkeep placeholders) counts — the AI
  // sometimes nests the app one level deep (recipe-box-app/…)
  if (walkHtmlFiles(projectId, '', 0).length) return true
  try {
    const tree = storage.listTree(projectId, '.') as any
    const files: string[] = []
    const flat = (node: any, base: string): void => {
      for (const child of node.children || []) {
        const p = base ? `${base}/${child.name}` : child.name
        if (child.isDirectory) { if (!p.includes('node_modules')) flat(child, p) }
        else files.push(p)
      }
    }
    flat(tree, '')
    return files.some(f => /\.(html|js|jsx|ts|tsx|dart|py|vue|css)$/.test(f) && !f.includes('node_modules'))
  } catch { return false }
}


export const VORTEX_TOOLS: Record<string, ToolDef> = {
  vortex_backend_provision: {
    name: 'vortex_backend_provision',
    description:
      'Provision a production backend for THIS app on the VORTEX SERVER (Firebase-alternative: auth + OTP verification, document database with security rules, file storage, realtime). ' +
      'Call this when the app needs any of: user login / signup / OTP verification, saving data (posts, orders, profiles, scores), file/image uploads, or realtime updates. ' +
      'Idempotent — calling it again returns the existing backend. Collections default to users/posts/settings; pass exactly the collections the app actually needs.',
    parameters: {
      type: 'object',
      properties: {
        collections: {
          type: 'array',
          items: { type: 'string' },
          description: 'Database collections the app needs, e.g. ["users","posts","comments"]. Default: users,posts,settings',
        },
      },
      required: [],
    },
    async execute(args: any, ctx: ProjectContext): Promise<ToolResult> {
      if (!vortexConfigured()) {
        return { ok: false, output: '', error: 'VORTEX ecosystem not wired (VORTEX_PLATFORM_KEY missing) — configure it in .env' }
      }
      const project = await db.project.findUnique({ where: { id: ctx.projectId } })
      if (!project) return { ok: false, output: '', error: 'project not found' }

      const collections: string[] = Array.isArray(args?.collections) && args.collections.length
        ? args.collections.map((c: unknown) => String(c).slice(0, 40)).slice(0, 20)
        : ['users', 'posts', 'settings']

      const r = await ensureVortexBackend(ctx.projectId, collections)
      if (!r.ok) return { ok: false, output: '', error: r.error || 'VaaS provision failed' }
      const payload = { vaasProjectId: r.vaasProjectId, clientKey: r.clientKey, baseUrl: r.baseUrl, collections }
      if (!r.provisioned) return { ok: false, output: '', error: 'provision did not complete' }
      return {
        ok: true,
        output:
          `VORTEX backend provisioned.\n` +
          `projectId: ${payload.vaasProjectId}\n` +
          `clientKey: ${payload.clientKey}\n` +
          `collections: ${(payload.collections || collections).join(', ')}\n` +
          `baseUrl: ${payload.baseUrl}\n` +
          `Written: vortex.config.js (client config) + VORTEX_BACKEND.md (SDK guide).\n` +
          `Wire the app to it: import the config, use x-vx-key for data calls, OTP endpoints for login. ` +
          `The ADMIN key is stored in project settings (never commit it into client code).`,
      }
    },
  },
}

/** DB file-row upsert best-effort (same contract as safeUpsert in tools.ts). */
async function safeUpsertFile(projectId: string, path: string, content: string) {
  try {
    await db.file.upsert({
      where: { projectId_path: { projectId, path } },
      create: { projectId, path, content, isDir: false },
      update: { content, isDir: false },
    })
  } catch {
    // disk write already succeeded; the DB row is best-effort
  }
}
