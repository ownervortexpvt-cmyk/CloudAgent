/**
 * PWA + SEO setup — turns any web project into an installable, SEO-ready app:
 *   - manifest.webmanifest (name, theme, icons)
 *   - icons 192/512 generated from a project logo or a branded fallback (sharp)
 *   - service worker (offline cache-first for static assets)
 *   - meta tags: description, theme-color, apple-touch, og:, twitter:, canonical
 *   - robots.txt + sitemap.xml (from project HTML files)
 * Idempotent: re-running refreshes files instead of duplicating tags.
 */
import fs from 'fs'
import path from 'path'
import { projectRoot, writeFile, existsFile, readFile } from './storage'

function pickAppName(root: string, fallback: string): string {
  try {
    const idx = path.join(root, 'index.html')
    if (fs.existsSync(idx)) {
      const m = fs.readFileSync(idx, 'utf8').match(/<title>([^<]+)<\/title>/i)
      if (m?.[1]) return m[1].trim().slice(0, 60)
    }
    const pkg = path.join(root, 'package.json')
    if (fs.existsSync(pkg)) {
      const j = JSON.parse(fs.readFileSync(pkg, 'utf8'))
      if (j.name) return j.name
    }
  } catch { /* ignore */ }
  return fallback
}

function makeIconSvg(name: string): string {
  const initial = (name.trim()[0] || 'A').toUpperCase()
  return `<svg xmlns="http://www.w3.org/2000/svg" width="512" height="512" viewBox="0 0 512 512">
<defs><linearGradient id="g" x1="0" y1="0" x2="1" y2="1">
<stop offset="0" stop-color="#6366f1"/><stop offset="1" stop-color="#22d3ee"/></linearGradient></defs>
<rect width="512" height="512" rx="96" fill="url(#g)"/>
<text x="256" y="340" font-family="system-ui,sans-serif" font-size="260" font-weight="800"
fill="#ffffff" text-anchor="middle">${initial}</text></svg>`
}

async function writeIcons(projectId: string, root: string, appName: string): Promise<string[]> {
  const sharp = (await import('sharp')).default
  const out: string[] = []
  const sourceCandidates = ['assets/icon.png', 'assets/logo.png', 'public/logo.png', 'icon.png', 'logo.png']
  let png: Buffer | null = null
  for (const c of sourceCandidates) {
    if (existsFile(projectId, c)) {
      try { png = await sharp(readFile(projectId, c)).png().toBuffer(); break } catch { /* try next */ }
    }
  }
  if (!png) {
    const svg = Buffer.from(makeIconSvg(appName))
    png = await sharp(svg).png().toBuffer()
  }
  for (const size of [192, 512]) {
    const buf = await sharp(png).resize(size, size, { fit: 'cover' }).png().toBuffer()
    const rel = `assets/icons/icon-${size}.png`
    writeFile(projectId, rel, buf)
    out.push(rel)
  }
  // favicon from the same source
  const fav = await sharp(png).resize(64, 64, { fit: 'cover' }).png().toBuffer()
  writeFile(projectId, 'assets/icons/favicon.png', fav)
  out.push('assets/icons/favicon.png')
  return out
}

const SW_JS = `// FocusSW — offline-first service worker (generated by AI App Builder)
const CACHE = 'app-v1';
const ASSETS = ['/', '/index.html', '/assets/icons/icon-192.png', '/assets/icons/icon-512.png'];
self.addEventListener('install', e => { e.waitUntil(caches.open(CACHE).then(c => c.addAll(ASSETS)).then(() => self.skipWaiting())) });
self.addEventListener('activate', e => { e.waitUntil(caches.keys().then(ks => Promise.all(ks.filter(k => k !== CACHE).map(k => caches.delete(k)))).then(() => self.clients.claim())) });
self.addEventListener('fetch', e => {
  if (e.request.method !== 'GET') return;
  e.respondWith(
    caches.match(e.request).then(hit => {
      const net = fetch(e.request).then(res => {
        if (res && res.status === 200 && e.request.url.startsWith(self.location.origin)) {
          const copy = res.clone(); caches.open(CACHE).then(c => c.put(e.request, copy));
        }
        return res;
      }).catch(() => hit);
      return hit || net;
    })
  );
});`

function injectMeta(html: string, appName: string, description: string): string {
  const tags: string[] = []
  const has = (re: RegExp) => re.test(html)
  const push = (tag: string, cond: RegExp) => { if (!cond.test(html)) tags.push(tag) }

  push(`<meta name="description" content="${esc(description)}">`, /name=["']description["']/i)
  push(`<meta name="theme-color" content="#6366f1">`, /name=["']theme-color["']/i)
  push(`<link rel="manifest" href="manifest.webmanifest">`, /rel=["']manifest["']/i)
  push(`<link rel="icon" href="assets/icons/favicon.png">`, /rel=["'](icon|shortcut icon)["']/i)
  push(`<link rel="apple-touch-icon" href="assets/icons/icon-192.png">`, /rel=["']apple-touch-icon["']/i)
  push(`<meta property="og:title" content="${esc(appName)}">`, /property=["']og:title["']/i)
  push(`<meta property="og:description" content="${esc(description)}">`, /property=["']og:description["']/i)
  push(`<meta name="twitter:card" content="summary">`, /name=["']twitter:card["']/i)

  if (!tags.length) return html
  if (html.includes('</head>')) return html.replace(/<\/head>/i, `${tags.join('\n')}\n</head>`)
  return html
}

function esc(s: string): string {
  return s.replace(/&/g, '&amp;').replace(/"/g, '&quot;').replace(/</g, '&lt;')
}

/** Inject the SW registration snippet once. */
function injectSWRegister(html: string): string {
  if (html.includes('serviceWorker.register')) return html
  const snip = `\n<script>if('serviceWorker' in navigator){addEventListener('load',()=>navigator.serviceWorker.register('sw.js').catch(()=>{}))}</script>`
  return html.includes('</body>') ? html.replace(/<\/body>/i, `${snip}</body>`) : html + snip
}

export async function pwaSeoSetup(projectId: string, opts: { appName?: string; description?: string } = {}): Promise<{ ok: true; files: string[]; appName: string }> {
  const root = projectRoot(projectId)
  const appName = opts.appName || pickAppName(root, 'My App')
  const description = opts.description || `${appName} — installable, offline-ready app.`
  const files: string[] = []

  const icons = await writeIcons(projectId, root, appName)
  files.push(...icons)

  const manifest = {
    name: appName,
    short_name: appName.slice(0, 12),
    description,
    start_url: '.',
    display: 'standalone',
    background_color: '#0f172a',
    theme_color: '#6366f1',
    icons: [
      { src: 'assets/icons/icon-192.png', sizes: '192x192', type: 'image/png', purpose: 'any maskable' },
      { src: 'assets/icons/icon-512.png', sizes: '512x512', type: 'image/png', purpose: 'any maskable' },
    ],
  }
  writeFile(projectId, 'manifest.webmanifest', JSON.stringify(manifest, null, 2))
  files.push('manifest.webmanifest')

  writeFile(projectId, 'sw.js', SW_JS)
  files.push('sw.js')

  // robots.txt + sitemap.xml (best-effort, from root HTML pages)
  const pages = ['index.html', 'about.html', 'contact.html', 'pricing.html'].filter(p => existsFile(projectId, p))
  writeFile(projectId, 'robots.txt', `User-agent: *\nAllow: /\nSitemap: sitemap.xml\n`)
  const sitemap = `<?xml version="1.0" encoding="UTF-8"?>\n<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n${pages.map(p => `  <url><loc>./${p === 'index.html' ? '' : p}</loc></url>`).join('\n')}\n</urlset>\n`
  writeFile(projectId, 'sitemap.xml', sitemap)
  files.push('robots.txt', 'sitemap.xml')

  // Meta injection into root HTML files
  const htmlTargets = ['index.html', 'src/index.html', 'dist/index.html', ...pages]
  for (const rel of [...new Set(htmlTargets)]) {
    const p = path.join(root, rel)
    if (!fs.existsSync(p)) continue
    const original = fs.readFileSync(p, 'utf8')
    const updated = injectSWRegister(injectMeta(original, appName, description))
    if (updated !== original) {
      fs.writeFileSync(p, updated)
      if (!files.includes(rel)) files.push(rel)
    }
  }

  return { ok: true, files, appName }
}
